# Writes src/generated/inflate_tables.h, a family file: the two codes of
# a fixed DEFLATE block (RFC 1951 section 3.2.6) as src/inflate.c's
# Huffman tables, built here exactly as its Build would build them, so a
# fixed block reads them in place of building both each time.
#
# usage: gen_inflate_tables.py [--check]
#   --check  fail when the file differs from what would be written

import os
import sys

GENERATED = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "generated")
MAX_BITS = 15
MAX_LITERALS = 288
FAST_BITS = 9


def build(lengths):
    """count, symbol, fastMask and fast as src/inflate.c's Build fills
    them."""
    count = [0] * (MAX_BITS + 1)
    for length in lengths:
        count[length] += 1
    count[0] = 0
    longest = MAX_BITS
    while longest > 1 and count[longest] == 0:
        longest -= 1
    fast_bits = min(longest, FAST_BITS)
    offsets = [0] * (MAX_BITS + 2)
    following = [0] * (MAX_BITS + 1)
    code = 0
    for length in range(1, MAX_BITS + 1):
        offsets[length + 1] = offsets[length] + count[length]
        code = (code + count[length - 1]) << 1
        following[length] = code
    symbol = [0] * MAX_LITERALS
    fast = [0] * (1 << FAST_BITS)
    for i, length in enumerate(lengths):
        if length == 0:
            continue
        symbol[offsets[length]] = i
        offsets[length] += 1
        c = following[length]
        following[length] += 1
        if length <= FAST_BITS:
            reversed_code = int(format(c, f"0{length}b")[::-1], 2)
            for at in range(reversed_code, 1 << fast_bits, 1 << length):
                fast[at] = i << 4 | length
    return count, symbol, (1 << fast_bits) - 1, fast


def array(name, values):
    lines = [f"    .{name} = {{"]
    for start in range(0, len(values), 12):
        lines.append("        " + ", ".join(str(v) for v in values[start:start + 12]) + ",")
    lines.append("    },")
    return lines


def table(name, comment, lengths):
    count, symbol, fast_mask, fast = build(lengths)
    lines = [f"// {comment}", f"static const Huffman {name} = {{"]
    lines += array("count", count) + array("symbol", symbol)
    lines.append(f"    .fastMask = {fast_mask},")
    lines += array("fast", fast)
    lines.append("};")
    return lines


def render():
    literals = [8] * 144 + [9] * 112 + [7] * 24 + [8] * 8
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        "// Generated by tools/gen_inflate_tables.py; do not edit. The codes of",
        "// a fixed block (RFC 1951 section 3.2.6) as src/inflate.c builds",
        "// them, included there after its Huffman type.",
        "// clang-format off",
        "",
        "#ifndef MAUL_UI_SRC_GENERATED_INFLATE_TABLES_H",
        "#define MAUL_UI_SRC_GENERATED_INFLATE_TABLES_H",
        "",
    ]
    lines += table("FIXED_LITERALS", "Literals 0 to 143 take 8 bits, 144 to 255 9, 256 to 279 7, the rest 8.",
                   literals)
    lines.append("")
    lines += table("FIXED_DISTANCES", "All 30 distance codes take 5 bits.", [5] * 30)
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit("usage: gen_inflate_tables.py [--check]")
    path = os.path.join(GENERATED, "inflate_tables.h")
    text = render()
    current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if check:
        if current != text:
            print("src/generated/inflate_tables.h is stale: run tools/gen_inflate_tables.py")
            return 1
        return 0
    if current != text:
        os.makedirs(GENERATED, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
